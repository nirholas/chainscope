#!/usr/bin/env node
/**
 * Generate the Cloudflare Pages Function that serves api/.
 *
 * The routes in api/ are already Workers-shaped: each exports a default
 * `handler(request)` returning a Response, and none import Node builtins. What
 * Pages needs is a single entry point with STATIC imports, because a Functions
 * bundle is built ahead of time and cannot resolve a dynamic path at runtime.
 * So this script walks api/, emits one import per route, and writes a catch-all
 * that dispatches to the right one.
 *
 * Route matching mirrors src-tauri/sidecar/local-api-server.mjs so a route
 * behaves identically under `npm run dev:api`, the desktop sidecar and Pages.
 *
 *   node scripts/build-pages-functions.mjs
 */
import { readdir, mkdir, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const API_DIR = path.join(ROOT, 'api');
const OUT_DIR = path.join(ROOT, 'functions', 'api');
const OUT_FILE = path.join(OUT_DIR, '[[path]].js');

const isBracketSegment = (part) => part.startsWith('[') && part.endsWith(']');

function routePriority(routePath) {
  return routePath
    .split('/')
    .filter(Boolean)
    .reduce((score, part) => {
      if (part.startsWith('[[...') && part.endsWith(']]')) return score + 0;
      if (part.startsWith('[...') && part.endsWith(']')) return score + 1;
      if (isBracketSegment(part)) return score + 2;
      return score + 10;
    }, 0);
}

/** Every api/**.js that is a route: not a partial (_), not a test. */
async function collectRoutes(dir, routes = []) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const absolute = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      await collectRoutes(absolute, routes);
      continue;
    }
    if (!entry.name.endsWith('.js')) continue;
    if (entry.name.startsWith('_')) continue;
    if (entry.name.includes('.test.')) continue;

    const relative = path.relative(API_DIR, absolute).replace(/\\/g, '/');
    routes.push({
      routePath: relative.replace(/\.js$/, '').replace(/\/index$/, ''),
      importPath: `../../api/${relative}`,
    });
  }
  return routes;
}

/** A route file is only usable if it actually exports a default handler. */
async function hasDefaultExport(importPath) {
  const absolute = path.join(OUT_DIR, importPath);
  const mod = await import(`file://${path.resolve(absolute)}`);
  return typeof mod.default === 'function';
}

const routes = (await collectRoutes(API_DIR)).sort(
  (a, b) => routePriority(b.routePath) - routePriority(a.routePath)
);

const usable = [];
const skipped = [];
for (const route of routes) {
  if (await hasDefaultExport(route.importPath)) usable.push(route);
  else skipped.push(route.routePath);
}

const imports = usable
  .map((route, i) => `import route${i} from '${route.importPath}';`)
  .join('\n');

const table = usable
  .map((route, i) => `  { path: ${JSON.stringify(route.routePath)}, handler: route${i} },`)
  .join('\n');

const generated = `// GENERATED by scripts/build-pages-functions.mjs. Do not edit by hand.
// Regenerate with: npm run build:functions
//
// Cloudflare Pages catch-all for /api/*. Routes are imported statically because
// a Functions bundle is built ahead of time and cannot resolve dynamic paths.

${imports}

const ROUTES = [
${table}
];

const isBracketSegment = (part) => part.startsWith('[') && part.endsWith(']');

/** Mirrors the matcher in src-tauri/sidecar/local-api-server.mjs. */
function matchRoute(routePath, pathname) {
  const routeParts = routePath.split('/').filter(Boolean);
  const pathParts = pathname.replace(/^\\/api/, '').split('/').filter(Boolean);

  let i = 0;
  let j = 0;
  while (i < routeParts.length && j < pathParts.length) {
    const routePart = routeParts[i];
    if (routePart.startsWith('[[...') && routePart.endsWith(']]')) return true;
    if (routePart.startsWith('[...') && routePart.endsWith(']')) return true;
    if (isBracketSegment(routePart)) {
      i += 1;
      j += 1;
      continue;
    }
    if (routePart !== pathParts[j]) return false;
    i += 1;
    j += 1;
  }

  if (i === routeParts.length && j === pathParts.length) return true;

  if (i === routeParts.length - 1) {
    const tail = routeParts[i];
    if (tail?.startsWith('[[...') && tail.endsWith(']]')) return true;
    if (tail?.startsWith('[...') && tail.endsWith(']')) return j < pathParts.length;
  }
  return false;
}

/**
 * Routes read configuration from process.env. Workers expose it as context.env
 * instead, so bridge the two before dispatching. Assigning per request is cheap
 * and keeps each isolate seeing the bindings it was actually given.
 */
function exposeEnv(env) {
  if (!env) return;
  const existing = globalThis.process?.env;
  if (existing && existing.__chainscopeBridged) return;
  globalThis.process = { ...globalThis.process, env: { ...env, __chainscopeBridged: true } };
}

export async function onRequest(context) {
  const { request, env } = context;
  exposeEnv(env);

  const pathname = new URL(request.url).pathname;
  const route = ROUTES.find((r) => matchRoute(r.path, pathname));

  if (!route) {
    return new Response(JSON.stringify({ error: 'Not found', endpoint: pathname }), {
      status: 404,
      headers: { 'Content-Type': 'application/json' },
    });
  }

  try {
    return await route.handler(request, context);
  } catch (error) {
    return new Response(
      JSON.stringify({ error: 'Handler failed', endpoint: pathname, detail: String(error?.message || error) }),
      { status: 500, headers: { 'Content-Type': 'application/json' } }
    );
  }
}
`;

if (!existsSync(OUT_DIR)) await mkdir(OUT_DIR, { recursive: true });
await writeFile(OUT_FILE, generated);

console.log(`[pages-functions] wrote ${path.relative(ROOT, OUT_FILE)}`);
console.log(`[pages-functions] ${usable.length} routes bundled`);
if (skipped.length) {
  console.log(`[pages-functions] ${skipped.length} skipped (no default export): ${skipped.join(', ')}`);
}
